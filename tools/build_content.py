#!/usr/bin/env python3
"""Generate the Android and web content from data/kspk.json.

One source of truth, two targets:

  data/kspk.json  ->  app/src/main/java/com/ceria/belajar/Content.java
                  ->  web/data.js

Adding a word means editing the JSON once and re-running this script; the APK and
the web app can never drift apart. The Java side keeps the same public shape the
rest of the app already compiles against (Content.LETTERS, Content.Item, and so
on) so the audio engine and the rewards system carry over untouched.

Usage
-----
  python3 tools/build_content.py          # regenerate both
  python3 tools/build_content.py --check  # fail if the generated files are stale
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data/kspk.json"
JAVA_OUT = ROOT / "app/src/main/java/com/ceria/belajar/Content.java"
WEB_OUT = ROOT / "web/data.js"

BANNER = ("// Generated by tools/build_content.py from data/kspk.json.\n"
          "// Edit the JSON, not this file.\n")

# Units whose items keep their own Java list, because existing screens take a
# list of Content.Item and are wired up by unit id.
